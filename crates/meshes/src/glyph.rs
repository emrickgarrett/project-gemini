pub fn measure(text: &str, scale: u32, advance: u32) -> u32 {
    text.chars().count() as u32 * advance.max(1) * scale.max(1)
}

pub fn blit(rgb: &mut [u8], width: u32, height: u32, x: i32, y: i32, text: &str, ink: [u8; 3], scale: u32, advance: u32) {
    let scale = scale.max(1);
    let advance = advance.max(1);
    for (index, ch) in text.chars().enumerate() {
        if !covers(ch) {
            continue;
        }
        let glyph = bits(ch);
        let gx = x + index as i32 * advance as i32 * scale as i32;
        for (row, bits) in glyph.iter().enumerate() {
            for col in 0..5 {
                if bits & (1 << (4 - col)) == 0 {
                    continue;
                }
                for oy in 0..scale {
                    for ox in 0..scale {
                        put(rgb, width, height, gx + col as i32 * scale as i32 + ox as i32, y + row as i32 * scale as i32 + oy as i32, ink);
                    }
                }
            }
        }
    }
}

fn put(rgb: &mut [u8], width: u32, height: u32, x: i32, y: i32, color: [u8; 3]) {
    if x < 0 || y < 0 || x >= width as i32 || y >= height as i32 {
        return;
    }
    let i = ((y as u32 * width) + x as u32) as usize * 3;
    if i + 2 < rgb.len() {
        rgb[i..i + 3].copy_from_slice(&color);
    }
}
